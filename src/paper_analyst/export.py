"""Markdown memo rendering and Obsidian vault export."""
from __future__ import annotations

import json
import re
from datetime import date
from pathlib import Path

from .memo import SECTIONS, ResearchMemo
from .models import Paper

NOT_STATED = "_Not stated in the available source text._"


def slugify(text: str, max_len: int = 80) -> str:
    """Obsidian-safe file name (no []#^|/\\:?* characters)."""
    text = re.sub(r'[\\/:*?"<>|#^\[\]]+', " ", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text[:max_len].rstrip(" .") or "untitled"


def note_name(paper: Paper) -> str:
    first = (paper.authors[0].split()[-1] if paper.authors else "Anon")
    year = paper.year or "n.d."
    return slugify(f"{first} {year} - {paper.title}")


def _yaml_str(v) -> str:
    return json.dumps(v, ensure_ascii=False)  # JSON strings are valid YAML scalars


def frontmatter(paper: Paper, memo: ResearchMemo | None) -> str:
    tags = ["paper", f"status/{paper.status}"]
    for name, d in (paper.relevance_breakdown or {}).get("topics", {}).items():
        if d.get("score", 0) >= 25:
            tags.append("topic/" + re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-"))
    lines = [
        "---",
        f"title: {_yaml_str(paper.title)}",
        "authors:" + ("".join(f"\n  - {_yaml_str(a)}" for a in paper.authors) if paper.authors else " []"),
        f"year: {paper.year if paper.year else 'null'}",
        f"date: {_yaml_str(paper.publication_date) if paper.publication_date else 'null'}",
        f"venue: {_yaml_str(paper.venue) if paper.venue else 'null'}",
        f"doi: {_yaml_str(paper.doi) if paper.doi else 'null'}",
        f"arxiv: {_yaml_str(paper.arxiv_id) if paper.arxiv_id else 'null'}",
        f"status: {paper.status}",
        f"relevance: {paper.relevance_score if paper.relevance_score is not None else 'null'}",
        "sources: [" + ", ".join(paper.sources) + "]",
    ]
    if memo:
        lines += [f"analyzer: {memo.analyzer}", f"model: {_yaml_str(memo.model) if memo.model else 'null'}",
                  f"source_text: {memo.source_text_kind}", f"analyzed: {memo.created_at[:10]}"]
    lines += ["tags:" + "".join(f"\n  - {t}" for t in tags), "---"]
    return "\n".join(lines)


def render_memo(paper: Paper, memo: ResearchMemo | None, obsidian: bool = True) -> str:
    out = [frontmatter(paper, memo), "", f"# {paper.title}", ""]
    out.append(f"**Authors:** {', '.join(paper.authors) or 'n/a'}  ")
    out.append(f"**Date:** {paper.publication_date or 'n/a'} · **Venue:** {paper.venue or 'n/a'}  ")
    ids = []
    if paper.doi:
        ids.append(f"[DOI: {paper.doi}](https://doi.org/{paper.doi})")
    if paper.arxiv_id:
        ids.append(f"[arXiv: {paper.arxiv_id}](https://arxiv.org/abs/{paper.arxiv_id})")
    ids += [f"[{k}]({v})" for k, v in paper.urls.items() if k not in ("openalex",)]
    out.append(f"**Links:** {' · '.join(ids) or 'n/a'}  ")
    out.append(f"**Status:** `{paper.status}` · **Relevance:** "
               f"{paper.relevance_score if paper.relevance_score is not None else 'n/a'}/100")
    out.append("")
    out.append("> [!info] How to read this memo\n"
               "> **Source-supported claims** are verbatim quotes from the "
               f"{(memo.source_text_kind if memo else 'abstract').replace('_', ' ')}, with locators. "
               "**Interpretations** are generated by the analyzer"
               f"{' (' + memo.analyzer + (', ' + memo.model if memo and memo.model else '') + ')' if memo else ''} "
               "and are *not* findings of the paper. No external citations are added.")
    out.append("")
    if memo is None:
        out += ["## Abstract", "", paper.abstract or NOT_STATED, ""]
        return "\n".join(out)

    for key, heading in SECTIONS.items():
        sec = memo.sections.get(key)
        out += [f"## {heading}", "", "**Source-supported claims**", ""]
        if sec and sec.claims:
            out += [f'- "{c.text}" — *{c.locator}*' for c in sec.claims]
        else:
            out.append(NOT_STATED)
        out.append("")
        if sec and sec.interpretations:
            out.append("> [!note] Interpretation (not stated in source)")
            for i in sec.interpretations:
                basis = f" _(Basis: {i.basis})_" if i.basis else ""
                out.append(f"> - {i.text}{basis}")
            out.append("")
    if memo.warnings:
        out += ["## Validation warnings", ""] + [f"- {w}" for w in memo.warnings] + [""]
    out += ["## Abstract (source text)", "", paper.abstract or NOT_STATED, ""]
    if paper.notes:
        out += ["## My notes", "", paper.notes, ""]
    return "\n".join(out)


def export_obsidian(items: list[tuple[Paper, ResearchMemo | None]], vault_dir: str | Path,
                    folder: str = "Papers") -> list[Path]:
    """Write one note per paper plus a Map-of-Content index note. Returns written paths."""
    root = Path(vault_dir)
    notes_dir = root / folder
    notes_dir.mkdir(parents=True, exist_ok=True)
    written, rows = [], []
    for paper, memo in items:
        name = note_name(paper)
        path = notes_dir / f"{name}.md"
        path.write_text(render_memo(paper, memo), encoding="utf-8")
        written.append(path)
        rows.append((paper, name))
    index = ["---", "tags:", "  - moc", "---", "", "# Paper index", "",
             f"_Generated {date.today().isoformat()} by paper-analyst._", "",
             "| Relevance | Paper | Year | Status |", "|---:|---|---|---|"]
    for paper, name in sorted(rows, key=lambda r: -(r[0].relevance_score or 0)):
        score = f"{paper.relevance_score:.0f}" if paper.relevance_score is not None else "–"
        index.append(f"| {score} | [[{folder}/{name}\\|{paper.title.replace('|', '/')}]] | "
                     f"{paper.year or ''} | {paper.status} |")
    idx_path = root / "Paper Index.md"
    idx_path.write_text("\n".join(index) + "\n", encoding="utf-8")
    written.append(idx_path)
    return written


def export_report(paper: Paper, report, vault_dir: str | Path, folder: str = "Reports") -> Path:
    """Write a deep report as an Obsidian note linked to the paper note."""
    from .report import render_report
    root = Path(vault_dir)
    (root / folder).mkdir(parents=True, exist_ok=True)
    path = root / folder / f"{note_name(paper)} - report.md"
    body = render_report(report, paper)
    body += f"\n\nPaper note: [[Papers/{note_name(paper)}]]\n"
    path.write_text(body, encoding="utf-8")
    return path
